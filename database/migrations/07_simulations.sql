-- 07_simulations.sql
-- Saves simulator execution history for reporting.

CREATE TABLE IF NOT EXISTS public.simulations (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  project_id UUID REFERENCES public.projects(id) ON DELETE CASCADE NOT NULL,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  start_node_id TEXT NOT NULL,
  change_type TEXT NOT NULL,
  payload JSONB,
  results JSONB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  FOREIGN KEY (start_node_id, project_id) REFERENCES public.nodes(id, project_id) ON DELETE CASCADE
);

-- CODE WALKTHROUGH
-- 1. Each row records one saved simulation, its project and user, the delayed starting task, and the proposed change.
-- 2. payload stores the proposed delay as JSON; results stores the calculated affected-task delays as JSON.
-- 3. created_at is generated by the database and is used to order the history page.
-- 4. The task foreign key prevents a simulation from referring to a nonexistent starting node in another project.
